/* ============================================================================
   AL-NASSIM storefront — EN | AR translation runtime
   ============================================================================
   Consumes window.NASSIM_I18N (generated by translation-system/apply.cjs from
   leo transila.xlsx — ONLY approved, conflict-free mappings).

   Toggle integration:
     The site's OWN shared language engine (dark-overrides.js →
     window.NassimLang) owns the EN | AR buttons, the localStorage
     'nassim-lang' preference and the visual active-side highlight. This
     runtime does NOT re-wire buttons; it listens to the site's
     'nassim-langchange' event and reads the stored preference on load.
     (Defensive fallback: if NassimLang is ever missing, a minimal structural
     binder reproduces the same behaviour.)

   Behaviour:
     - EN (default): page shows its original English. Nothing is modified.
     - AR: SPLIT TRANSLATION UNITS ARE PROCESSED FIRST, GENERICALLY. An
       element whose COMPLETE rendered text exactly equals a mapping key
       (e.g. <a>Houseware<br><span>Equipment</span></a> for the key
       "houseware equipment") is translated as ONE whole unit — its Arabic is
       distributed across the original <br> segments — BEFORE any walker
       touches its individual child text nodes. Child nodes therefore never
       pre-translate and destroy the unit match (the old
       "الأدوات المنزلية / EQUIPMENT" leftover). Only after every whole unit
       is handled does the text-node walker translate remaining standalone
       nodes (exact full-text match only — no substring/replace matching).
       Also translates visible placeholders + document title and keeps
       applying to nodes added later.
     - AR RTL — TEXT LEVEL, NEVER STRUCTURAL:
       The document direction is deliberately NOT flipped (no
       <html dir="rtl">): a document-wide RTL direction mirrors flex/grid
       rows, navigation, category cards and hero compositions, which must
       keep their exact English physical positions. Instead every translated
       Arabic run is explicitly RTL at the text level:
         - an element that carries ONLY text (optionally simple inline text
           styling / <br> line structure) is marked .nassim-rtl
           (direction: rtl + unicode-bidi: isolate) and, where English was
           left/start-anchored, .nassim-rtl-ta (text-align: right);
         - a text run that lives beside icons/arrows/other components (mixed
           containers, flex/grid parents) is isolated by an inline
           <span dir="rtl"> wrapper that never reorders siblings.
       Numbers, prices and Latin product codes inside Arabic remain readable
       LTR runs (bidi algorithm inside the isolated RTL context).
     - AR -> EN: restores every original text node/placeholder/title EXACTLY,
       unwraps every isolation wrapper, removes every RTL class, restores
       split-unit DOM byte-for-byte and returns <html lang="en"> (the dir
       attribute is never touched). English HTML source is never edited.
   ========================================================================== */
(function () {
  'use strict';
  if (window.__nassimI18n) return; // idempotent
  window.__nassimI18n = true;

  var MAP = window.NASSIM_I18N || {};
  /* Arabic -> distinct original English casings. Generated exclusively from
     leo transila.xlsx; contains ONLY unambiguous values (one Arabic value
     mapping to exactly one English key). Used narrowly to restore dynamically
     rebuilt mobile-nav content that the site re-creates from already-
     translated desktop DOM (never as a general translator). */
  var REVERSE = window.NASSIM_I18N_REVERSE || {};

  /* Same normalization rules as the pipeline:
     NFC, collapse whitespace, trim, case-fold. Punctuation/digits preserved. */
  function norm(s) {
    return String(s == null ? '' : s).normalize('NFC').replace(/\s+/g, ' ').trim().toLowerCase();
  }

  var lookup = {};
  Object.keys(MAP).forEach(function (k) { lookup[norm(k)] = MAP[k]; });

  function storedLang() {
    try { return localStorage.getItem('nassim-lang') === 'ar' ? 'ar' : 'en'; } catch (e) { return 'en'; }
  }
  var current = storedLang();

  var originals = new Map();    // text node -> original English nodeValue
  var phOriginals = new Map();  // element -> original placeholder
  var elementLedger = new Map(); // element -> DocumentFragment with its EXACT original children
  /* RTL marks applied by this runtime, for EXACT English restoration:
     attrLedger: element -> {hadClass, rtl, ta} for .nassim-rtl[.nassim-rtl-ta]
     wrapLedger: isolation wrapper span -> its original text node */
  var attrLedger = new Map();
  var wrapLedger = new Map();
  /* Provenance of translations actually applied in this page load:
     Arabic value (trimmed) -> the exact original English text it replaced.
     Built ONLY from leo transila.xlsx-derived translations; provides perfect
     casing for the narrow rebuilt-nav restore. */
  var reverseSeen = new Map();
  var titleOriginal = null;
  var observer = null;
  var stats = window.__i18nStats = { splitsTranslated: 0, rtlMarked: 0, rtlWrapped: 0, reverseRestored: 0, reverseLeftArabic: 0 };

  var SKIP = { SCRIPT: 1, STYLE: 1, NOSCRIPT: 1, TEMPLATE: 1, IFRAME: 1, SVG: 1, CANVAS: 1 };
  // form field values are business data; their visible default text stays English
  var FIELD = { TEXTAREA: 1, SELECT: 1, OPTION: 1 };

  /* ---------- text-level RTL marking ----------
     RTL is applied to TEXT containers only — never to structural layout.
     A direction on a flex/grid container reorders its children (mirroring);
     a direction on an element that also holds icons/arrows/components would
     swap their sides. Both are forbidden: such runs get an inline
     <span dir="rtl"> isolation wrapper instead, which cannot reorder
     anything. See rtl-overrides.css for the class definitions (AR-scoped). */
  var RTL_CLASS = 'nassim-rtl';       // direction: rtl + unicode-bidi: isolate
  var RTL_TA_CLASS = 'nassim-rtl-ta'; // + text-align: right (EN was left/start)
  var INLINE_TEXT_TAGS = { BR: 1, B: 1, I: 1, EM: 1, STRONG: 1, U: 1, SMALL: 1, MARK: 1, ABBR: 1, SUB: 1, SUP: 1 };

  function isPlainTextBox(el) {
    if (!el || el.nodeType !== 1 || SKIP[el.tagName]) return false;
    var d;
    try { d = getComputedStyle(el).display; } catch (e) { return false; }
    if (/flex|grid/.test(d)) return false; // structural: direction would mirror it
    var n = 0;
    for (var c = el.firstElementChild; c; c = c.nextElementSibling) {
      if (!INLINE_TEXT_TAGS[c.tagName]) return false; // icons/arrows/components: wrap instead
      if (++n > 12) return false;
    }
    return true;
  }

  function markElRtl(el) {
    var rec = attrLedger.get(el);
    if (!rec) {
      rec = { hadClass: el.hasAttribute('class'), rtl: false, ta: false, ctx: false, dir: false, anchor: false, fiEnd: false, jcEnd: false, styleAttr: undefined };
      attrLedger.set(el, rec);
    }
    if (!rec.rtl) { el.classList.add(RTL_CLASS); rec.rtl = true; stats.rtlMarked++; }
    if (!rec.ta) {
      var ta = '';
      try { ta = getComputedStyle(el).textAlign; } catch (e) {}
      if (ta === 'left' || ta === 'start') { el.classList.add(RTL_TA_CLASS); rec.ta = true; }
    }
    groupPending.add(el);
  }

  function wrapNodeRtl(node) {
    if (node.__i18nWrapped) return;
    var span = document.createElement('span');
    span.setAttribute('dir', 'rtl'); // inline isolate: Arabic flows RTL, siblings keep their positions
    span.className = RTL_CLASS;
    node.parentNode.insertBefore(span, node);
    span.appendChild(node);
    node.__i18nWrapped = true;
    wrapLedger.set(span, node);
    stats.rtlWrapped++;
    groupPending.add(span);
  }

  /* ---------- content-group RTL (the CTA/button rule) ----------
     A translated element never floats alone: it belongs to a visual content
     group (eyebrow + heading + paragraph + CTA row) inside its component.
     In Arabic the WHOLE group must share one alignment system — a heading
     moving right while its CTA stays at the English left anchor is exactly
     the split this prevents. From every marked element we therefore climb
     the ancestor chain and mark the group containers, stopping hard at:
       - structural containers (nav/header/footer/main/section/…): the page
         skeleton never participates in text-group alignment;
       - any ancestor whose subtree holds MEDIA (img/svg/canvas/video or a
         url() background) — that is the card/slide/component boundary, and
         the physical image composition must not be touched;
       - any ancestor whose subtree holds UNTRANSLATED visible Latin text —
         unmatched English stays English and keeps its English positioning.
     Marked group containers get (see rtl-overrides.css):
       .nassim-rtl-ctx      text-align: right (centered designs stay center)
       .nassim-rtl-dir      direction: rtl — BLOCK/flex-COLUMN containers only
                           (a direction on a flex ROW would reorder children)
       .nassim-rtl-anchor   margin-left: auto — content-sized groups hug the
                           RIGHT side of their component (the flex item text
                           column of a carousel/hero slide)
       .nassim-rtl-fi-end   align-items: flex-end — flex-COLUMN groups whose
                           children were left-anchored (cross axis is
                           horizontal there; rows are never touched this way)
       .nassim-rtl-jc-end   justify-content: flex-end — flex-ROW groups whose
                           children hugged left (CTA button rows): the cluster
                           moves right, the button ORDER is preserved
     Absolutely positioned overlays anchored with `left` only are mirrored
     to `right` (left:auto) with the exact computed offset, ledgered for
     byte-exact English restoration. The background image / card / grid /
     slide composition is never modified. */
  var RTL_CTX_CLASS = 'nassim-rtl-ctx';
  var RTL_DIR_CLASS = 'nassim-rtl-dir';
  var RTL_ANCHOR_CLASS = 'nassim-rtl-anchor';
  var RTL_FI_END_CLASS = 'nassim-rtl-fi-end';
  var RTL_JC_END_CLASS = 'nassim-rtl-jc-end';
  var STRUCTURAL_STOP = { NAV: 1, HEADER: 1, FOOTER: 1, MAIN: 1, SECTION: 1, ASIDE: 1, ARTICLE: 1, FORM: 1, TABLE: 1, UL: 1, OL: 1, LI: 1, DL: 1, HGROUP: 1 };
  var ctxMemo = new Map(); // element -> true (group container) / false (boundary); cleared on restore
  /* Climbs are DEFERRED: hasMediaOrEnglish() must judge "untranslated
     English" against the FINAL Arabic page. Climbing per-unit mid-walk would
     see a unit's still-English siblings and wrongly boundary-lock the whole
     group container in the memo. All origins are collected during the
     translation pass and climbed once, after it completes. */
  var groupPending = new Set();
  function flushGroupMarks() {
    if (!groupPending.size) return;
    var items = [];
    groupPending.forEach(function (el) { items.push(el); });
    groupPending.clear();
    items.forEach(function (el) {
      if (el && el.isConnected !== false) markGroupContext(el);
    });
  }

  function hasMediaOrEnglish(el) {
    if (el.querySelector('img,svg,canvas,video,iframe,picture,object')) return true;
    var bg = null;
    try { bg = getComputedStyle(el).backgroundImage; } catch (e) {}
    if (bg && bg.indexOf('url(') !== -1) return true;
    var w = document.createTreeWalker(el, NodeFilter.SHOW_TEXT);
    var n;
    while ((n = w.nextNode())) {
      var v = n.nodeValue;
      if (!v || v.length < 3 || !/[A-Za-z]{3,}/.test(v)) continue;
      if (/[\u0600-\u06FF]/.test(v)) continue;          // translated value (mixed Arabic/Latin content)
      var p = n.parentElement;
      if (p && isIconEl(p)) continue;                    // icon ligatures are not words
      return true;                                       // untranslated English: boundary
    }
    return false;
  }

  function markCtxEl(a) {
    var rec = attrLedger.get(a);
    if (!rec) {
      rec = { hadClass: a.hasAttribute('class'), rtl: false, ta: false, ctx: false, dir: false, anchor: false, fiEnd: false, jcEnd: false, styleAttr: undefined };
      attrLedger.set(a, rec);
    }
    var cs;
    try { cs = getComputedStyle(a); } catch (e) { return; }
    var disp = cs.display || '';
    var flexish = disp.indexOf('flex') !== -1;
    var isFlexRow = flexish && cs.flexDirection.indexOf('column') !== 0;
    var isFlexCol = flexish && cs.flexDirection.indexOf('column') === 0;
    if (!rec.ctx) {
      var ta = cs.textAlign;
      if (ta !== 'center' && ta !== 'right' && ta !== 'end' && ta !== 'justify') {
        a.classList.add(RTL_CTX_CLASS); rec.ctx = true;
      }
    }
    if (!rec.dir && !isFlexRow) { a.classList.add(RTL_DIR_CLASS); rec.dir = true; }
    if (!rec.anchor) {
      var w = a.getBoundingClientRect().width;
      var pw = a.parentElement ? a.parentElement.getBoundingClientRect().width : 0;
      // A CENTERED group (text-align:center) is symmetric by design — the
      // right-anchor margin would shift the whole block (e.g. the category
      // page hero heading) off the page center. Only left-hugging groups
      // (left/start text alignment) are anchored to the right.
      var centeredGroup = cs.textAlign === 'center';
      if (!centeredGroup && w > 0 && pw > 0 && w < pw * 0.95) { a.classList.add(RTL_ANCHOR_CLASS); rec.anchor = true; }
    }
    if (!rec.fiEnd && isFlexCol && cs.alignItems === 'flex-start') { a.classList.add(RTL_FI_END_CLASS); rec.fiEnd = true; }
    if (!rec.jcEnd && isFlexRow && (cs.justifyContent === 'flex-start' || cs.justifyContent === 'start' || cs.justifyContent === 'normal' || cs.justifyContent === 'left')) {
      a.classList.add(RTL_JC_END_CLASS); rec.jcEnd = true;
    }
    if (rec.styleAttr === undefined) {
      var pos = cs.position;
      if (pos === 'absolute' || pos === 'fixed') {
        var lSet = cs.left !== 'auto', rSet = cs.right !== 'auto';
        if (lSet && !rSet) {
          rec.styleAttr = a.getAttribute('style'); // exact original (string|null) for restore
          var px = parseFloat(cs.left) || 0;
          a.style.left = 'auto';
          a.style.right = px + 'px';
        }
      }
    }
  }

  function markGroupContext(startEl) {
    var a = startEl;
    for (var depth = 0; depth < 10; depth++) {
      a = a.parentElement;
      if (!a || a === document.body || a === document.documentElement) return;
      if (STRUCTURAL_STOP[a.tagName]) return;
      // Navigation chrome (top bar, drawer) NEVER participates in content-
      // group repositioning: its items must keep their exact English physical
      // positions. Nav text is already RTL via the element-level marks.
      if (a.closest('nav')) return;
      // Any fixed/sticky chrome (top bar, bottom mobile bar, floating
      // widgets) is page furniture, not a content group.
      var posA;
      try { posA = getComputedStyle(a).position; } catch (e) { posA = ''; }
      if (posA === 'fixed' || posA === 'sticky') return;
      var memo = ctxMemo.get(a);
      if (memo === false) return;
      if (memo === true) return; // already a marked group container; its ancestors were handled then
      if (hasMediaOrEnglish(a)) { ctxMemo.set(a, false); return; }
      ctxMemo.set(a, true);
      markCtxEl(a);
    }
  }

  /* A split translation unit may carry the RTL direction ON THE UNIT itself
     when the unit is not a structural (flex/grid) container and every
     element inside it is part of the translated text structure (<br> lines
     and the carriers of the segment text nodes). A unit's COMPLETE text is
     the mapping key, so an icon/arrow/component sibling could not even be
     part of a matched unit — there is nothing else inside to reorder. The
     direction then only changes how the unit's own lines flow (right-to-
     left, right-anchored via .nassim-rtl-ta); the unit's position and its
     <br> line structure are untouched. */
  function isUnitRtlSafe(el, carriers) {
    if (!el || el.nodeType !== 1 || SKIP[el.tagName]) return false;
    var d;
    try { d = getComputedStyle(el).display; } catch (e) { return false; }
    if (/flex|grid/.test(d)) return false;
    var ok = true;
    (function scan(node) {
      if (!ok) return;
      for (var c = node.firstElementChild; c; c = c.nextElementSibling) {
        if (c.tagName === 'BR') continue;
        if (carriers.has(c)) { scan(c); if (!ok) return; }
        else { ok = false; return; } // styling/component element that is not a text carrier
      }
    })(el);
    return ok;
  }

  /* Mark the run carried by a translated text node (plain text-node path). */
  function markNodeRtl(node) {
    var p = node.parentElement;
    if (!p || p.nodeType !== 1) return;
    var d = p.getAttribute && p.getAttribute('dir');
    if (d === 'rtl' || p.classList.contains(RTL_CLASS)) return; // already inside an RTL context
    if (d === 'ltr') { wrapNodeRtl(node); return; } // explicitly pinned LTR element: isolate the run only
    if (isPlainTextBox(p)) markElRtl(p);
    else wrapNodeRtl(node);
  }

  function skipNode(node) {
    var el = node.parentElement;
    while (el) {
      if (SKIP[el.tagName]) return true;
      el = el.parentElement;
    }
    return false;
  }

  /* AR-mode text-node processor: (1) translate full-text key matches, and
     (2) give EVERY Arabic run an RTL text context — RTL is a property of
     the script, not of the translation. (2) also covers "born-Arabic"
     content the site rebuilds from already-translated DOM (mobile-nav.js
     drawer), which can never match an English key. Idempotent; every mark
     is ledgered for exact English restoration. */
  function processTextNode(node) {
    if (node.nodeType !== 3) return;
    translateTextNode(node);
    var v = node.nodeValue;
    if (v && /[\u0600-\u06FF]/.test(v) && !skipNode(node)) markNodeRtl(node);
  }

  /* Currency token pass: prices are rendered statically and dynamically
     ("KD 25.000", "1.250 KD/piece") and mostly do not exist as whole-text
     mapping keys. In AR the standalone token KD/KWD becomes د.ك wherever it
     appears inside an otherwise unchanged text run; the ledgered original
     restores it exactly on AR -> EN. Word boundaries keep codes like "1KD"
     untouched. */
  var CURRENCY_TOKEN = /\b(?:KWD|KD)\b/g;
  var CURRENCY_AR = '\u062F.\u0643';

  /* SHARED EMPTY-STATE PATTERN: the empty state is the SAME message on every
     listing page — English "No products found." (the exact key in
     NASSIM_I18N) and Arabic "لم يتم العثور على أي منتجات.". Any residual
     category-form string ("No Kitchenware products found.", e.g. from an
     older cached script) resolves to the SAME approved Arabic — the category
     name is deliberately dropped; no per-category keys exist. */
  var EMPTY_STATE_RE = /^no\s+(?:.*?)\s*products\s+found\.?$/i;
  var EMPTY_STATE_AR = 'لم يتم العثور على أي منتجات.';
  function emptyStateAr(v) {
    return EMPTY_STATE_RE.exec(String(v).replace(/\s+/g, ' ').trim()) ? EMPTY_STATE_AR : null;
  }

  /* PRODUCTS COUNT PATTERN: the listing header count renders as one composed
     text node ("12 products"), which can never exact-match the approved
     "products" key. Compose from the number + the approved NASSIM_I18N
     mapping ("products" -> "منتجات"); no count logic is touched — this only
     re-words the rendered label in AR. Singular "1 product" has no approved
     mapping and stays English. */
  var PRODUCTS_COUNT_RE = /^(\d[\d,]*)\s+products$/i;
  function productsCountAr(v) {
    var m = PRODUCTS_COUNT_RE.exec(String(v).replace(/\s+/g, ' ').trim());
    if (!m) return null;
    var ar = lookup['products'];
    if (ar == null) return null;
    return m[1] + ' ' + ar;
  }

  /* LISTING COUNT PATTERN: the listing header count renders as one composed
     text node ("number of items: 12"), which can never exact-match the
     approved "number of items" key. Compose from the approved mapping
     ("number of items" -> "عدد العناصر") + the live number. The logical
     string "عدد العناصر: 12" inside the RTL-isolated count element renders
     visually as "12 :عدد العناصر" — number stays an LTR run, exactly as
     approved. */
  var ITEMS_COUNT_RE = /^number of items:\s*(\d[\d,]*)$/i;
  function itemsCountAr(v) {
    var m = ITEMS_COUNT_RE.exec(String(v).replace(/\s+/g, ' ').trim());
    if (!m) return null;
    var ar = lookup['number of items'];
    if (ar == null) return null;
    return ar + ': ' + m[1];
  }

  /* ORDER-SHEET QUANTITY PATTERN: order pages render the product-row label
     as one composed text node ("Quantity: 3"), which can never exact-match
     the approved "quantity: 1" key (exact match still wins for quantity 1).
     Compose from the approved mapping ("quantity" -> "الكمية") + the live
     number, following the same pattern as itemsCountAr above. */
  var QUANTITY_RE = /^quantity:\s*(\d+)$/i;
  function quantityAr(v) {
    var m = QUANTITY_RE.exec(String(v).replace(/\s+/g, ' ').trim());
    if (!m) return null;
    var ar = lookup['quantity'];
    if (ar == null) return null;
    return ar + ': ' + m[1];
  }

  /* ORDER-SHEET CODE/MODEL PATTERN: item rows render the label and the live
     code as one composed text node ("Code/MODEL : ND-1197"), which can never
     exact-match the approved "code/model:" key. Compose from the approved
     mapping ("code/model:" -> "الكود/الموديل") + the live code, following the
     same pattern as quantityAr above. The embedded Latin code keeps its LTR
     run inside the RTL-marked node. */
  var CODE_MODEL_RE = /^code\/model\s*:\s*(\S.*)$/i;
  function codeModelAr(v) {
    var m = CODE_MODEL_RE.exec(String(v).replace(/\s+/g, ' ').trim());
    if (!m) return null;
    var ar = lookup['code/model:'];
    if (ar == null) return null;
    return ar + ': ' + m[1];
  }

  function translateTextNode(node) {
    if (node.nodeType !== 3) return;
    var v = node.nodeValue;
    if (!v || !v.trim()) return;
    if (skipNode(node)) return;
    var parentEl = node.parentElement;
    if (parentEl && FIELD[parentEl.tagName]) return;
    // ICON LIGATURES ARE NOT WORDS: a Material Symbols span renders its
    // text content as a glyph (e.g. "remove" = the minus icon). Translating
    // it would replace the icon with Arabic text — never touch them.
    if (parentEl && isIconEl(parentEl)) return;
    var ar = lookup[norm(v)];
    if (ar == null) ar = emptyStateAr(v); // shared "No [Category] products found." composition
    if (ar == null) ar = productsCountAr(v); // composed "N products" count label
    if (ar == null) ar = itemsCountAr(v); // composed "number of items: N" listing count
    if (ar == null) ar = quantityAr(v); // composed "Quantity: N" order-sheet label
    if (ar == null) ar = codeModelAr(v); // composed "Code/MODEL : X" order-sheet label
    /* TRAILING-COLON FALLBACK: sidebar headings render as "FILTER BY :" while
       the approved key is "filter by". On an exact miss, retry the text
       without its trailing " :" and append the colon to the approved Arabic
       ("تصفية حسب :"). Fires only after a full-text miss, so every mapping
       that already matches is untouched. */
    if (ar == null) {
      var mColon = /^(.*\S)\s*:$/.exec(v.trim());
      if (mColon) {
        var base = lookup[norm(mColon[1])];
        if (base != null) ar = base + ' :';
      }
    }
    var out = ar != null ? ar : v;
    out = out.replace(CURRENCY_TOKEN, CURRENCY_AR);
    if (out === v) return; // no mapping and no currency token — nothing to change
    if (!originals.has(node)) originals.set(node, v);
    if (ar != null) reverseSeen.set(ar.trim(), v.trim()); // provenance: exact original casing
    node.nodeValue = out;
    node.__i18nAr = out; // what WE set — lets the observer recognise our own writes
    markNodeRtl(node);
  }

  function restoreTextNode(node) {
    if (!originals.has(node)) return;
    node.nodeValue = originals.get(node);
    if (node.__i18nAr) delete node.__i18nAr;
    originals.delete(node);
  }

  function walkText(root, fn) {
    var w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
    var n;
    while ((n = w.nextNode())) fn(n);
  }

  /* Complete rendered text of an element. For elements being rendered,
     innerText is exactly what the pipeline extractor captured (visible text,
     <br> as line breaks). For elements NOT being rendered (the desktop nav
     at mobile width, offscreen drawer copies), Chrome's innerText falls back
     to textContent — which loses the <br> separators ("HousewareEquipment"
     would never match "houseware equipment"). Those get a reconstruction
     that walks the child nodes and treats <br>/node boundaries as spaces. */
  function renderedText(el) {
    var t = null;
    try { t = el.innerText; } catch (e) {}
    var rendered = false;
    try { rendered = el.getClientRects().length > 0; } catch (e) {}
    if (t != null && t.trim() && rendered) return t;
    var out = '';
    (function rec(node) {
      for (var c = node.firstChild; c; c = c.nextSibling) {
        if (c.nodeType === 3) { out += c.nodeValue + ' '; }
        else if (c.nodeType === 1) {
          if (SKIP[c.tagName]) continue;
          if (c.tagName === 'BR') { out += ' '; continue; }
          rec(c);
          out += ' ';
        }
      }
    })(el);
    return out.replace(/\s+/g, ' ');
  }

  function translatePlaceholders(root) {
    var list = (root.matches && root.matches('input[placeholder],textarea[placeholder]')
      ? [root] : []);
    list = list.concat([].slice.call(root.querySelectorAll ? root.querySelectorAll('input[placeholder],textarea[placeholder]') : []));
    list.forEach(function (el) {
      var p = el.getAttribute('placeholder');
      if (!p || !p.trim()) return;
      var ar = lookup[norm(p)];
      if (!ar) return;
      // bidi-isolate the Arabic inside the (LTR) control so multi-word
      // placeholders read correctly; the original is restored from the ledger.
      var val = /[\u0600-\u06FF]/.test(ar) ? '\u2067' + ar + '\u2069' : ar;
      if (!phOriginals.has(el)) phOriginals.set(el, p);
      el.setAttribute('placeholder', val);
    });
  }

  function restorePlaceholders() {
    phOriginals.forEach(function (orig, el) { el.setAttribute('placeholder', orig); });
    phOriginals.clear();
  }

  /* ---------- element-level translation units (split text) ----------
     Some approved strings are rendered from MULTIPLE text nodes, e.g.:
         <a>Supermarket<br><span>Equipment</span></a>
     The extractor captures the COMPLETE rendered element text, so the same
     unit is approved in the workbook. Rule: if an element's COMPLETE
     normalized rendered text exactly equals a mapping key (innermost such
     element, no unrelated content — guaranteed because the full rendered
     text IS the key), translate the WHOLE unit BEFORE any walker translates
     its child nodes (call order in applyAr/observer guarantees this), so a
     standalone child key like "houseware" can never pre-translate and break
     the unit match. Exact original children are kept in the element ledger
     so AR->EN restores the DOM byte-for-byte. */
  function translateSplitElements(root) {
    var all = root.nodeType === 1
      ? [root].concat([].slice.call(root.querySelectorAll('*')))
      : [].slice.call(root.querySelectorAll('*'));
    var units = [];
    for (var i = 0; i < all.length; i++) {
      var el = all[i];
      if (el.nodeType !== 1 || SKIP[el.tagName]) continue;
      if (el.__i18nEl) continue;
      // ICON LIGATURES ARE NOT WORDS: never treat an icon (or any element
      // containing one — a unit replacement would destroy the icon) as a
      // translation unit. Ligature names like "remove" must stay intact.
      if (isIconEl(el) || el.querySelector('.material-symbols-outlined')) continue;
      // FUNCTIONAL CHILDREN ARE OFF-LIMITS: an element containing id-hooked
      // children (JS read/write hooks, e.g. cart summary amounts) must never
      // be replaced as a unit — the replacement would delete those hooks and
      // break page logic. Such text is still translated per text node by the
      // walker when each node individually matches a key.
      if (el.querySelector('[id]')) continue;
      if (el.textContent && el.textContent.length > 200) continue; // translation units are small
      var t = renderedText(el);               // COMPLETE rendered text (visible only)
      if (!t || !t.trim() || t.length > 120) continue;
      var key = norm(t);
      var ar = lookup[key];
      if (!ar || ar === t.trim()) continue;    // no key / identical numeric value
      // innermost carrier: no descendant renders the same complete text
      var ds = el.querySelectorAll('*');
      var inner = true;
      for (var j = 0; j < ds.length; j++) {
        var dt = renderedText(ds[j]);
        if (dt && norm(dt) === key) { inner = false; break; }
      }
      if (!inner) continue;
      units.push({ el: el, ar: ar.trim() });
    }
    units.forEach(function (u) {
      var el = u.el;
      var frag = document.createDocumentFragment();
      for (var k = 0; k < el.childNodes.length; k++) frag.appendChild(el.childNodes[k].cloneNode(true));
      elementLedger.set(el, frag);             // exact original DOM (B)
      reverseSeen.set(u.ar, renderedText(el).replace(/s+/g, ' ').trim()); // provenance

      // ONE logical RTL unit: the COMPLETE approved Arabic string goes into
      // a single text node. The English <br>/span line structure exists only
      // for English typography and is an English RESTORATION instruction —
      // never an Arabic line-break instruction. The Arabic is never divided,
      // cropped, distributed across segments, or given manual <br> tags; the
      // browser renders the complete string inside the RTL text container
      // (direction: rtl + unicode-bidi: isolate + text-align: right) and any
      // line wrapping is the browser's own, from the available width. The
      // exact original children stay in the element ledger for byte-exact
      // AR->EN restoration.
      while (el.firstChild) el.removeChild(el.firstChild);
      var tn = document.createTextNode(u.ar);
      el.appendChild(tn);
      // one RTL text container for the whole unit — text level only
      if (!el.hasAttribute('dir') && isUnitRtlSafe(el, new Set([el]))) markElRtl(el);
      else wrapNodeRtl(tn);
      el.__i18nEl = true;
      stats.splitsTranslated++;
    });
  }

  function restoreSplitElements() {
    elementLedger.forEach(function (frag, el) {
      while (el.firstChild) el.removeChild(el.firstChild);
      el.appendChild(frag);                    // exact original structure, nodes, casing
      delete el.__i18nEl;
    });
    elementLedger.clear();
  }

  function restoreRtlMarks() {
    wrapLedger.forEach(function (node, span) {
      if (span.parentNode) span.parentNode.replaceChild(node, span); // exact original node back in place
    });
    wrapLedger.clear();
    attrLedger.forEach(function (rec, el) {
      el.classList.remove(RTL_CLASS, RTL_TA_CLASS, RTL_CTX_CLASS, RTL_DIR_CLASS, RTL_ANCHOR_CLASS, RTL_FI_END_CLASS, RTL_JC_END_CLASS);
      if (rec.styleAttr !== undefined) {
        if (rec.styleAttr === null) el.removeAttribute('style');
        else el.setAttribute('style', rec.styleAttr);
      }
      if (!rec.hadClass && !el.getAttribute('class')) el.removeAttribute('class'); // byte-exact restore
    });
    attrLedger.clear();
    ctxMemo.clear();
    groupPending.clear();
  }

  /* ---------- narrow reverse restore (C) ----------
     mobile-nav.js rebuilds the drawer's department accordion from the
     desktop nav each time it renders (buildDepartmentsHTML), and splits the
     department name across per-word <span>s (cat.name.split(/\s+/)). Opened
     while AR, that content is born Arabic — sometimes word-split — and is
     unknown to the ledgers. Restore ONLY here, ONLY values this runtime
     translated itself (exact provenance) or that exist verbatim in the
     generated unambiguous reverse map. Never applied outside the drawer. */
  function englishForArabic(arTrimmed) {
    // STRICT RULE: only values present in the generated reverse map (i.e.
    // UNAMBIGUOUS in leo transila.xlsx: one Arabic -> exactly one English
    // key) may be restored. Excel-ambiguous and unknown values are left
    // unchanged and counted — never guessed.
    var variants = REVERSE[arTrimmed];
    if (!variants || !variants.length) return null;
    // Provenance only refines the CASING of the same unambiguous unit: the
    // exact original English this runtime translated earlier in this load.
    if (reverseSeen.has(arTrimmed)) {
      var seen = reverseSeen.get(arTrimmed);
      if (norm(seen) === arTrimmed.toLowerCase()) return seen; // same unit, exact casing
    }
    return variants[0]; // Excel casing fallback
  }

  function isIconEl(el) {
    return el.classList && el.classList.contains('material-symbols-outlined');
  }

  /* text nodes of el, excluding icon-ligature subtrees (their ligature text
     is not customer-facing words) */
  function contentTextNodes(el) {
    var out = [];
    (function rec(node) {
      for (var c = node.firstChild; c; c = c.nextSibling) {
        if (c.nodeType === 3) { if (c.nodeValue.trim()) out.push(c); continue; }
        if (c.nodeType !== 1) continue;
        if (SKIP[c.tagName] || isIconEl(c)) continue;
        rec(c);
      }
    })(el);
    return out;
  }

  /* ---------- narrow restore of rebuilt drawer content ----------
     mobile-nav.js re-renders the drawer's departments from the DESKTOP nav
     (parseCategories → buildDepartmentsHTML, with cat.name.split(/\s+/)
     word spans). Rendered while AR, that content is born Arabic and unknown
     to the ledgers. Restore it deterministically by re-reading the SAME
     desktop source in its restored English state — triggers by index,
     subcategory links by href — mirroring the site's own build exactly.
     No Arabic→English guessing is involved: the English comes from the
     restored desktop DOM itself. Any leftover not covered positionally
     falls back to the validated unambiguous reverse map, then stops. */
  function desktopExtractName(link) {
    var parts = [];
    for (var c = 0; c < link.childNodes.length; c++) {
      var node = link.childNodes[c];
      var t = node.textContent ? node.textContent.trim() : '';
      if (t) parts.push(t); // BR nodes have empty textContent, skipped as in the site
    }
    return parts.join(' ');
  }

  function reverseRestoreRebuiltNav() {
    var scope = document.getElementById('mobile-nav-drawer');
    if (!scope) return;

    // the site's build inputs, read from the restored (English) desktop nav
    var cats = [];
    var triggers = document.querySelectorAll('.dropdown-trigger');
    for (var i = 0; i < triggers.length; i++) {
      var link = triggers[i].querySelector('a');
      if (!link) continue;
      var subcats = [];
      var subLinks = triggers[i].querySelectorAll('.dropdown-menu > ul > li > a');
      for (var j = 0; j < subLinks.length; j++)
        subcats.push(subLinks[j].textContent.replace(/\u203a/g, '').trim());
      cats.push({ name: desktopExtractName(link), subcats: subcats });
    }
    var last = triggers.length ? triggers[triggers.length - 1] : null;
    if (last) {
      var sib = last.nextElementSibling;
      while (sib) {
        if (sib.tagName === 'A' && !sib.classList.contains('dropdown-trigger'))
          cats.push({ name: desktopExtractName(sib), subcats: [] });
        sib = sib.nextElementSibling;
      }
    }

    var items = scope.querySelectorAll('.mobile-accordion-item');
    for (var i2 = 0; i2 < items.length && i2 < cats.length; i2++) {
      var cat = cats[i2];
      // accordion trigger: per-word spans of cat.name. If the site re-rendered
      // the drawer while AR, the span structure follows the Arabic word count;
      // rebuild it exactly as buildDepartmentsHTML does for the English name
      // (first word plain span, remaining words in the small muted spans).
      var trig = items[i2].querySelector('.mobile-accordion-trigger');
      if (trig && cat.name) {
        var words = cat.name.split(/\s+/);
        var wrap = null;
        for (var s = 0; s < trig.children.length; s++) {
          var ch = trig.children[s];
          if (isIconEl(ch)) continue;
          if (ch.classList.contains('flex') && ch.classList.contains('flex-col')) { wrap = ch; break; }
        }
        if (wrap) {
          while (wrap.firstChild) wrap.removeChild(wrap.firstChild);
          for (var p = 0; p < words.length; p++) {
            var sp = document.createElement('span');
            if (p > 0) sp.className = 'text-[11px] font-semibold text-gray-500 dark:text-gray-400';
            sp.textContent = words[p];
            wrap.appendChild(sp);
          }
          stats.reverseRestored++;
        } else {
          // unexpected shape: text-only restore, structure untouched
          var tn = contentTextNodes(trig);
          if (tn.length === words.length) {
            for (var k = 0; k < tn.length; k++) tn[k].nodeValue = words[k];
            stats.reverseRestored++;
          } else if (tn.length) {
            tn[0].nodeValue = cat.name;
            for (var k2 = 1; k2 < tn.length; k2++) tn[k2].nodeValue = '';
            stats.reverseRestored++;
          }
        }
      }
      // accordion body links: built in the same order as the desktop sublinks
      var bodyLinks = items[i2].querySelectorAll('.mobile-accordion-body a');
      for (var b = 0; b < bodyLinks.length && b < cat.subcats.length; b++) {
        var tn2 = contentTextNodes(bodyLinks[b]);
        if (!tn2.length) continue;
        tn2[0].nodeValue = cat.subcats[b];
        for (var k3 = 1; k3 < tn2.length; k3++) tn2[k3].nodeValue = '';
        stats.reverseRestored++;
      }
    }

    // fallback for any remaining Arabic in the drawer not covered above
    var nodes = [];
    var w = document.createTreeWalker(scope, NodeFilter.SHOW_TEXT, null);
    var n;
    while ((n = w.nextNode())) nodes.push(n);
    nodes.forEach(function (node) {
      var v = node.nodeValue;
      if (!v || !v.trim() || !/[\u0600-\u06FF]/.test(v)) return;
      if (node.parentElement && isIconEl(node.parentElement)) return;
      var en = englishForArabic(v.trim());
      if (!en) { stats.reverseLeftArabic++; return; } // ambiguous/unknown: leave, never guess
      node.nodeValue = en;
      stats.reverseRestored++;
    });
  }

  /* ---------- MOBILE DRAWER DEPARTMENT LABELS: one single-line phrase ----------
     mobile-nav.js rebuilds the drawer accordion from the desktop nav and
     splits each department name into per-word <span>s (English two-line
     typography). When rebuilt while AR, those spans are born Arabic and
     render as stacked fragments. Coalesce the Arabic word spans into ONE
     span carrying the COMPLETE phrase as a single logical RTL text unit on
     a single line (nowrap via AR-scoped CSS). Idempotent: skips English
     labels and already-coalesced labels; the EN restore is unaffected
     because reverseRestoreRebuiltNav rebuilds the English spans from the
     desktop DOM. Approved translation data is never modified. */
  function coalesceDrawerArabicLabels() {
    var scope = document.getElementById('mobile-nav-drawer');
    if (!scope) return;
    var wraps = scope.querySelectorAll('.mobile-accordion-trigger .flex.flex-col');
    for (var i = 0; i < wraps.length; i++) {
      var spans = [].slice.call(wraps[i].querySelectorAll('span')).filter(function (s) {
        return !s.classList.contains('material-symbols-outlined');
      });
      var filled = spans.filter(function (s) { return s.textContent.trim(); });
      if (filled.length <= 1) continue; // already one unit (or empty)
      var allArabic = filled.every(function (s) { return /[\u0600-\u06FF]/.test(s.textContent); });
      if (!allArabic) continue;         // English label keeps its designed structure
      var phrase = filled.map(function (s) { return s.textContent.trim(); }).join(' ');
      filled[0].textContent = phrase;
      for (var j = 1; j < filled.length; j++) filled[j].textContent = '';
    }
  }

  /* ---------- AR MINIMUM FONT SIZE ----------
     Arabic must never render smaller than the site's reference CTA
     ("تصفح أدوات المطبخ", the hero button). Any text element whose computed
     font-size is below that reference gets an inline minimum font-size;
     the original value is ledgered for exact EN restoration. Icons are
     never scaled, and the reference is measured live so it stays
     responsive (the CTA itself is 8px on small screens, 10px on desktop).
     Idempotent: elements already at/above the minimum are never touched. */
  var MINFS_REF_TEXT = 'تصفح أدوات المطبخ';
  var minFsLedger = new Map(); // element -> original inline font-size ('' if none)

  function minFsReference() {
    var els = document.querySelectorAll('a,button,span,div');
    for (var i = 0; i < els.length; i++) {
      var e = els[i];
      if (e.children.length === 0 && e.textContent.trim() === MINFS_REF_TEXT && e.getBoundingClientRect().width > 0) {
        var fs = parseFloat(getComputedStyle(e).fontSize);
        if (fs > 0) return fs;
      }
    }
    return 10; // defensive fallback
  }

  function enforceMinFontSize(root) {
    var min = minFsReference();
    var scope = (root && root.querySelectorAll) ? root : document.body;
    if (!scope || scope.nodeType !== 1) return;
    var list = [scope].concat([].slice.call(scope.querySelectorAll('*')));
    for (var i = 0; i < list.length; i++) {
      var el = list[i];
      if (SKIP[el.tagName] || isIconEl(el)) continue;      // icons keep their glyph size
      if (minFsLedger.has(el) || !(el.textContent || '').trim()) continue;
      var fs = parseFloat(getComputedStyle(el).fontSize);
      if (fs && fs < min) {
        minFsLedger.set(el, el.style.fontSize || '');
        el.style.fontSize = min + 'px';
      }
    }
  }

  function restoreMinFontSize() {
    minFsLedger.forEach(function (orig, el) {
      if (orig) el.style.fontSize = orig;
      else el.style.removeProperty('font-size');
    });
    minFsLedger.clear();
  }

  function applyAr() {
    if (!titleOriginal) titleOriginal = document.title;
    var arTitle = lookup[norm(titleOriginal)];
    if (arTitle) document.title = arTitle;
    // GENERIC ORDER — whole split units FIRST: a unit's complete text must
    // still match its key when it is identified, so no child text node may
    // be translated before the unit is claimed (e.g. the standalone key
    // "houseware" inside <a>Houseware<br><span>Equipment</span></a>).
    translateSplitElements(document.body);
    walkText(document.body, processTextNode);
    translatePlaceholders(document.body);
    coalesceDrawerArabicLabels();
    enforceMinFontSize(document.body);
    flushGroupMarks(); // group containers are marked AFTER the whole page is Arabic
    startObserver();
  }

  /* ---------- narrow restore of cloned listing category chips ----------
     Category/listing pages clone their filter chips from the page's HIDDEN
     .subcat-tabs source (.category-btn / .subcat-cat-chip, matched by
     data-slug — the internal filter identifier, never translated text).
     When a page LOADS in AR, the clones are born Arabic and are unknown to
     the ledgers, so AR -> EN left them Arabic. Restore them deterministically
     from the RESTORED English source. The 'check' icon ligature span is
     untouched; the label may be a direct text node or an AR isolation
     wrapper, so the non-icon content is rebuilt as one English text node. */
  function reverseRestoreListingChips() {
    var source = document.querySelector('.subcat-tabs');
    if (!source) return;
    var bySlug = {};
    var srcBtns = source.querySelectorAll('.category-btn[data-slug], .subcat-cat-chip[data-slug]');
    for (var i = 0; i < srcBtns.length; i++) {
      bySlug[srcBtns[i].getAttribute('data-slug')] = srcBtns[i].textContent.replace(/check$/, '').trim();
    }
    var chips = document.querySelectorAll('.category-btn, .subcat-cat-chip');
    for (var j = 0; j < chips.length; j++) {
      var chip = chips[j];
      if (source.contains(chip)) continue;
      var en = bySlug[chip.getAttribute('data-slug')];
      if (!en) continue;
      if (chip.textContent.replace(/check$/, '').trim() === en) continue;
      var ref = chip.firstChild;
      for (var c = chip.childNodes.length - 1; c >= 0; c--) {
        var nd = chip.childNodes[c];
        if (nd.nodeType === 1 && isIconEl(nd)) { ref = nd; continue; }
        chip.removeChild(nd);
      }
      chip.insertBefore(document.createTextNode(en), ref);
      stats.reverseRestored++;
    }
  }

  function restoreEn() {
    stopObserver();
    // 1. remove every RTL mark this runtime applied (wrappers unwrapped to
    //    the exact original nodes, classes removed — byte-exact English DOM),
    // 2. ledger restores (exact text nodes + exact split-element DOM),
    // 3. then the narrow reverse restore for rebuilt mobile-nav content.
    restoreRtlMarks();
    originals.forEach(function (orig, node) {
      node.nodeValue = orig;
      if (node.__i18nAr) delete node.__i18nAr;
    });
    originals.clear();
    restorePlaceholders();
    restoreSplitElements();
    restoreMinFontSize();
    reverseRestoreRebuiltNav();
    reverseRestoreListingChips();
    if (titleOriginal !== null) { document.title = titleOriginal; titleOriginal = null; }
  }

  function startObserver() {
    if (observer || !window.MutationObserver) return;
    var pending = false;
    var scheduled = new Set();
    var flush = function () {
      pending = false;
      scheduled.forEach(function (node) {
        scheduled.delete(node);
        if (!node.isConnected) return;
        if (node.nodeType === 3) {
          // If the node currently shows OUR Arabic, this record was our own
          // write — nothing to do. If it shows anything else, site JS has
          // replaced the text with fresh English: that becomes the new
          // restorable original, then we translate the new text.
          if (originals.has(node) && node.__i18nAr && node.nodeValue === node.__i18nAr) return;
          if (originals.has(node)) { originals.set(node, node.nodeValue); delete node.__i18nAr; }
          processTextNode(node);
        } else {
          // same generic order as applyAr: whole split units before walkers,
          // group marks deferred until the batch is fully translated
          translateSplitElements(node);
          walkText(node, processTextNode);
          translatePlaceholders(node);
          coalesceDrawerArabicLabels(); // drawer may be (re)built while AR
          enforceMinFontSize(node);     // dynamically added text obeys the minimum too
          flushGroupMarks();
        }
      });
    };
    observer = new MutationObserver(function (muts) {
      for (var i = 0; i < muts.length; i++) {
        var m = muts[i];
        if (m.type === 'characterData') scheduled.add(m.target);
        else for (var j = 0; j < m.addedNodes.length; j++) scheduled.add(m.addedNodes[j]);
      }
      if (scheduled.size && !pending) { pending = true; setTimeout(flush, 50); }
    });
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
  }

  function stopObserver() { if (observer) { observer.disconnect(); observer = null; } }

  /* ---------- direction ----------
     TEXT direction is handled per translated run (see RTL marking above).
     The document/html direction is deliberately NOT switched to RTL: doing
     so mirrors the entire physical composition (nav rows, grids, cards,
     heroes) which must stay exactly where English put them. Only the
     language attribute and the AR styling hook change. */
  function applyDir() {
    var html = document.documentElement;
    if (current === 'ar') {
      html.setAttribute('lang', 'ar');
      html.classList.add('lang-ar');
    } else {
      html.setAttribute('lang', 'en');
      html.classList.remove('lang-ar');
    }
  }

  /* ---------- language changes ---------- */
  function activate(lang) {
    lang = lang === 'ar' ? 'ar' : 'en';
    if (current === lang && initialized) return;
    current = lang;
    initialized = true;
    applyDir();
    if (current === 'ar') applyAr();
    else restoreEn();
  }
  var initialized = false;

  // The site's engine dispatches on window; keep a document listener too so
  // the runtime also works if any page ever dispatches there.
  window.addEventListener('nassim-langchange', function (e) {
    activate(e && e.detail && e.detail.lang ? e.detail.lang : storedLang());
  });
  document.addEventListener('nassim-langchange', function (e) {
    activate(e && e.detail && e.detail.lang ? e.detail.lang : storedLang());
  });

  // Defensive fallback ONLY for pages without the site's engine. The check
  // happens AT CLICK TIME: dark-overrides.js may load after this script, so
  // window.NassimLang can appear later — never double-toggle with it.
  function fallbackBind() {
    document.addEventListener('click', function (ev) {
      if (window.NassimLang) return; // the site's engine owns the toggles
      var t = ev.target;
      while (t && t !== document) {
        if (t.tagName === 'BUTTON') {
          var en = false, ar = false;
          var spans = t.querySelectorAll('span');
          for (var i = 0; i < spans.length; i++) {
            var s = (spans[i].textContent || '').trim().toUpperCase();
            if (s === 'EN') en = true; else if (s === 'AR') ar = true;
          }
          if (en && ar && spans.length <= 4) {
            ev.stopPropagation();
            activate(current === 'ar' ? 'en' : 'ar');
            try { localStorage.setItem('nassim-lang', current); } catch (e) {}
            return;
          }
        }
        t = t.parentElement;
      }
    }, true);
  }

  /* ---------- carousel visual behaviour ----------
     Deliberately UNTOUCHED: the original carousel is an opacity crossfade
     with its own controls/swipe/autoplay; its visual direction, image
     composition and text-overlay placement are identical in EN and AR
     (the document direction no longer flips at all in AR, and the slide row
     is defensively pinned LTR in rtl-overrides.css). Arabic headings,
     paragraphs and CTAs flow RTL inside the SAME physical text boxes via
     the runtime's text-level marks. No swipe remapping, no mirroring. */

  /* ---------- boot ---------- */
  function init() {
    // Defence-in-depth against browser auto-translate (static meta + html
    // attribute are patched by apply.cjs; enforce at runtime too in case a
    // page ships without them). Auto-translation mutating the DOM would
    // corrupt the EN<->AR ledgers.
    try {
      document.documentElement.setAttribute('translate', 'no');
      if (!document.querySelector('meta[name="google"][content="notranslate"]')) {
        var m = document.createElement('meta');
        m.setAttribute('name', 'google');
        m.setAttribute('content', 'notranslate');
        document.head.appendChild(m);
      }
    } catch (e) {}
    fallbackBind();
    applyDir();
    if (current === 'ar') applyAr();
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
})();
